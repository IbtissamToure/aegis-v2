const numLocale = () => (LANG === "ar" ? "ar-SA-u-nu-latn" : "en-US");

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === "ar" ? "rtl" : "ltr";
  root.querySelectorAll("[data-i18n]").forEach((n) => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll("[data-i18n-attr]").forEach((n) => {
    n.dataset.i18nAttr.split(";").forEach((pair) => { const [a, k] = pair.split(":"); if (a && k) n.setAttribute(a.trim(), t(k.trim())); });
  });
  document.querySelectorAll("[data-lang-switch]").forEach((b) => { b.textContent = t("lang.switch"); b.setAttribute("aria-label", t("lang.switch.label")); });
}
const LANG_LISTENERS = [];
function onLangChange(fn) { LANG_LISTENERS.push(fn); }
function setLang(l) {
  LANG = l === "ar" ? "ar" : "en";
  try { localStorage.setItem(LANG_KEY, LANG); } catch (_) { /* storage blocked */ }
  applyI18n();
  LANG_LISTENERS.forEach((fn) => { try { fn(LANG); } catch (e) { console.error(e); } });
}
document.addEventListener("click", (e) => {
  const b = e.target.closest("[data-lang-switch]");
  if (b) setLang(LANG === "en" ? "ar" : "en");
});
